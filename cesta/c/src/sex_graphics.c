/*2D framebuffer primitives and 8x8 CP437 bitmap font, translated from crates/sex-graphics/src/{lib,font}.rs.*/
static uint32_t min_u32(uint32_t a, uint32_t b) {
  return a < b ? a : b;
}
static uint32_t saturating_sub_u32(uint32_t a, uint32_t b) {
  return a > b ? a - b : 0u;
}
WindowBuffer window_buffer_new(uint32_t *virtual_address, uint32_t width, uint32_t height, uint32_t stride) {
  return (WindowBuffer) {
    .virtual_address = virtual_address,.width = width,.height = height,.stride = stride
  };
}
void window_buffer_draw_pixel(WindowBuffer *wb, uint32_t x, uint32_t y, uint32_t color) {
  if (x < wb->width && y < wb->height) {
    size_t offset = (size_t)(y * wb->stride + x);
    wb->virtual_address[offset] = color;
  }
}
uint32_t window_buffer_draw_pixel_safe(WindowBuffer *wb, uint32_t x, uint32_t y, uint32_t color) {
  if (wb->virtual_address == NULL || (x >= wb->width || y >= wb->height)) return 0u;
  size_t offset = (size_t)(y * wb->stride + x);
  wb->virtual_address[offset] = color;
  return color;
}
uint32_t window_buffer_read_pixel_safe(const WindowBuffer *wb, uint32_t x, uint32_t y) {
  if (wb->virtual_address == NULL || (x >= wb->width || y >= wb->height)) return 0u;
  size_t offset = (size_t)(y * wb->stride + x);
  return wb->virtual_address[offset];
}
/*Rust's `(rect.x as i32 + rect.width as i32).max(0) as u32` wraps in 32-bit two's complement and clamps negative sums to 0.*/
void window_buffer_draw_rect(WindowBuffer *wb, SexGraphicsRect rect, uint32_t color) {
  uint32_t start_x = rect.x;
  uint32_t start_y = rect.y;
  uint32_t sum_x = rect.x + rect.width;
  uint32_t sum_y = rect.y + rect.height;
  uint32_t end_x = sum_x < 0x80000000u ? sum_x : 0u;
  uint32_t end_y = sum_y < 0x80000000u ? sum_y : 0u;
  uint32_t limit_x = min_u32(end_x, wb->width);
  uint32_t limit_y = min_u32(end_y, wb->height);
  for (uint32_t y = start_y; y < limit_y; y += 1) for (uint32_t x = start_x; x < limit_x; x += 1) window_buffer_draw_pixel(wb, x, y, color);
}
void window_buffer_clear(WindowBuffer *wb, uint32_t color) {
  window_buffer_draw_rect(wb, (SexGraphicsRect) {
    .x = 0,.y = 0,.width = wb->width,.height = wb->height
  }, color);
}
void sex_graphics_draw_char(WindowBuffer *fb, uint32_t x, uint32_t y, uint8_t ch, uint32_t fg, bool has_bg, uint32_t bg) {
  size_t idx = (size_t)(ch & 0x7Fu);
  for (size_t row = 0; row < SEX_GRAPHICS_FONT_ROWS; ++row) {
    uint8_t bits = SEX_GRAPHICS_FONT[idx][row];
    uint32_t py = y + (uint32_t) row;
    for (uint32_t col = 0; col < SEX_GRAPHICS_CHAR_W; col += 1) {
      uint32_t px = x + col;
      if ((bits >> (7u - col) & 1u) != 0) window_buffer_draw_pixel(fb, px, py, fg);
      else if (has_bg) window_buffer_draw_pixel(fb, px, py, bg);
    }
  }
}
uint32_t sex_graphics_draw_str(WindowBuffer *fb, uint32_t x, uint32_t y, const uint8_t *s, size_t len, uint32_t fg, bool has_bg, uint32_t bg) {
  uint32_t cx = x;
  for (size_t i = 0; i < len; ++i) {
    sex_graphics_draw_char(fb, cx, y, s[i], fg, has_bg, bg);
    cx += SEX_GRAPHICS_CHAR_W;
  }
  return saturating_sub_u32(cx, x);
}
uint32_t sex_graphics_str_width(size_t byte_len) {
  return (uint32_t) byte_len * SEX_GRAPHICS_CHAR_W;
}
