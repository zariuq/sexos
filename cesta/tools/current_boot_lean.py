#!/usr/bin/env python3
"""Generate a finite logical BOOT certificate from the actual Cesta tables."""
import argparse
from pathlib import Path
import re
import subprocess

HERE=Path(__file__).resolve().parent.parent


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--cesta',type=Path,required=True)
    ap.add_argument('--data',type=Path,default=HERE/'interfaces/kernel_current.data')
    ap.add_argument('output',type=Path);args=ap.parse_args()
    def rows(table,*columns):
        p=subprocess.run([str(args.cesta),'tables','rows',str(args.data),table,*columns],cwd=HERE,capture_output=True,text=True,check=True)
        return [r.split() for r in re.findall(r'\(Row ([^()]*)\)',p.stdout)]
    domains=rows('Domains','id','name','key','layout','active');ids={name:ident for ident,name,*_ in domains}
    routes=[(ids[h],slot,ids[t]) for h,slot,t in rows('Routes','holder','slot','target')]
    apps=[(ids[target],*rest) for target,*rest in rows('Apps','target','ordinal','predecessor','logical')]
    kinds={'ENTROPY_SOURCE':'.entropy','CLOCK_SOURCE':'.clock','TRUST_POLICY':'.trust'}
    sources=[(ids[h],slot,kinds[kind],ids[c]) for h,slot,kind,c in rows('Sources','holder','slot','kind','consumer')]
    domain_text=',\n  '.join('⟨'+', '.join((i,k,l,a))+'⟩' for i,n,k,l,a in domains)
    route_text=', '.join('('+', '.join(r)+')' for r in routes)
    app_text=', '.join('⟨'+', '.join(r)+'⟩' for r in apps)
    source_text=', '.join('⟨'+', '.join(r)+'⟩' for r in sources)
    text='''import Mettapedia.Machines.Kernel.BootAuthority

/-!
# Current SexOS logical BOOT declarations

Generated by the SexOS Cesta current_boot_lean tool from kernel_current.data.
The C rows and this certificate share those declarations. This certifies the
finite logical graph and initial admission constraints. It does not interpret
native C, page tables, private-image transitions or hardware keys as authority.
Reserved incarnations intentionally share keys; only initial admissions have
distinct keys. Typed source declarations have separate slot/role constraints;
they are not treated as communication edges. Actual task attachment, native
construction/PTE checks and hardware-source integrity are separate evidence.
-/

set_option autoImplicit false
set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace Mettapedia.Machines.Kernel.SexOSCurrentBoot
open Mettapedia.Machines.Kernel

structure Domain where
  id : Nat
  key : Nat
  layout : Nat
  initial : Bool
  deriving DecidableEq

structure App where
  target : Nat
  ordinal : Nat
  predecessor : Nat
  logical : Nat
  deriving DecidableEq

inductive SourceKind where
  | entropy | clock | trust
  deriving DecidableEq

structure Source where
  holder : Nat
  slot : Nat
  kind : SourceKind
  consumer : Nat
  deriving DecidableEq

def domains : List Domain :=
  [DOMAINS]

def routes : List (Nat × Nat × Nat) :=
  [ROUTES]

def apps : List App :=
  [APPS]

def sources : List Source :=
  [SOURCES]

def actions : List (BootAuthority.Action Nat) :=
  routes.map fun r => .install r.1 r.2.1 ⟨.ring r.2.2, true⟩

def authority : BootAuthority.Table Nat :=
  BootAuthority.run 1025 BootAuthority.empty (actions ++ [.finishBoot])

theorem domain_ids_unique : (domains.map Domain.id).Nodup := by decide
theorem layouts_unique : (domains.map Domain.layout).Nodup := by decide
theorem domain_bounds : ∀ d ∈ domains, 0 < d.id ∧ d.id < 1024 ∧ 0 < d.key ∧ d.key < 16 := by decide
theorem initial_count : (domains.filter (·.initial)).length = 15 := by decide
theorem admitted_keys_unique : ∀ a ∈ domains, ∀ b ∈ domains,
    a.initial = true → b.initial = true → a.key = b.key → a.id = b.id := by decide
theorem dormant_keys_are_reused : ∃ a ∈ domains, ∃ b ∈ domains,
    a.id ≠ b.id ∧ a.key = b.key ∧ a.initial = true ∧ b.initial = false := by decide
theorem route_slots_unique : (routes.map fun r => (r.1, r.2.1)).Nodup := by decide
theorem route_subjects_registered : ∀ r ∈ routes,
    (∃ d ∈ domains, d.id = r.1) ∧ (∃ d ∈ domains, d.id = r.2.2) ∧
    0 < r.2.1 ∧ r.2.1 < 1025 := by decide
theorem app_lineage : ∀ a ∈ apps,
    (a.ordinal = 0 → a.predecessor = 0 ∧ a.logical = a.target) ∧
    (a.ordinal ≠ 0 → ∃ old ∈ apps, old.target = a.predecessor ∧
      old.logical = a.logical ∧ old.ordinal + 1 = a.ordinal) := by decide
theorem source_slots_unique : (sources.map fun s => (s.holder, s.slot)).Nodup := by decide
theorem required_source_grants :
    ⟨13, 60, .entropy, 15⟩ ∈ sources ∧ ⟨13, 61, .clock, 15⟩ ∈ sources ∧
    ⟨13, 62, .trust, 15⟩ ∈ sources ∧ ⟨6, 61, .clock, 6⟩ ∈ sources := by decide
theorem source_subjects_registered : ∀ s ∈ sources,
    (∃ d ∈ domains, d.id = s.holder) ∧ (∃ d ∈ domains, d.id = s.consumer) ∧
    0 < s.slot ∧ s.slot < 1025 := by decide
theorem sources_do_not_replace_routes : ∀ s ∈ sources, ∀ r ∈ routes,
    s.holder ≠ r.1 ∨ s.slot ≠ r.2.1 := by decide
theorem source_roles : ∀ s ∈ sources,
    (s.holder = 13 ∧ s.consumer = 15 ∧
      ((s.kind = .entropy ∧ s.slot = 60) ∨ (s.kind = .clock ∧ s.slot = 61) ∨
       (s.kind = .trust ∧ s.slot = 62))) ∨
    (s.holder = 6 ∧ s.consumer = 6 ∧ s.kind = .clock ∧ s.slot = 61) := by decide
theorem browser_has_no_source_grant : ∀ s ∈ sources, s.holder ≠ 15 := by decide
theorem sealed : authority.sealed = true := by decide
theorem all_routes_installed : ∀ r ∈ routes,
    authority.caps r.1 r.2.1 = some ⟨.ring r.2.2, true⟩ := by decide
theorem demand_clients_reach_pager :
    authority.caps 10 2 = some ⟨.ring 14, true⟩ ∧
    authority.caps 15 2 = some ⟨.ring 14, true⟩ := by decide
theorem runtime_cannot_extend (more : List (BootAuthority.Action Nat)) :
    BootAuthority.run 1025 authority more = authority :=
  BootAuthority.run_sealed 1025 authority more sealed

#print axioms admitted_keys_unique
#print axioms all_routes_installed
#print axioms runtime_cannot_extend
#print axioms source_roles
#print axioms required_source_grants
end Mettapedia.Machines.Kernel.SexOSCurrentBoot
'''
    text=text.replace('DOMAINS',domain_text).replace('ROUTES',route_text).replace('APPS',app_text).replace('SOURCES',source_text)
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(text)


if __name__=='__main__':main()
