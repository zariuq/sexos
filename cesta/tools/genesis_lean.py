#!/usr/bin/env python3
"""Generate the Lean instance of the kernel's genesis table (interfaces/kernel.data).

The kernel compiles the same table through cesta export-header; this script reads it through
`cesta tables rows` and writes a Lean module that instantiates Mettapedia's single-address-space
kernel with it.

usage: genesis_lean.py --cesta CESTA OUTPUT.lean
"""

import argparse
from pathlib import Path
import re
import subprocess

HERE = Path(__file__).resolve().parent.parent


def rows(cesta, table, *columns):
    out = subprocess.run([cesta, "tables", "rows", "interfaces/kernel.data", table, *columns],
                         cwd=HERE, capture_output=True, text=True, check=True).stdout
    return [r.split() for r in re.findall(r"\(Row ([^()]*)\)", out)]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cesta", required=True)
    parser.add_argument("output", type=Path)
    parser.add_argument("--network", action="store_true", help="include the explicit native-network grants")
    args = parser.parse_args()
    domains = rows(args.cesta, "Domains", "id", "name")
    grants = rows(args.cesta, "RingGrants", "holder", "slot", "target")
    if args.network:
        grants += rows(args.cesta, "NetworkGrants", "holder", "slot", "target")
    names = [name for _, name in domains]
    lines = []
    w = lines.append
    w("import Mettapedia.Machines.Kernel.SingleAddressSpace")
    w("")
    w("/-!")
    w("# The SexOS boot genesis")
    w("")
    w("Generated by `cesta/tools/genesis_lean.py` (SexOS fork, branch `cesta`) from the genesis table")
    w("`interfaces/kernel.data`, which the Cesta kernel compiles into its boot grants. Do not edit.")
    w("")
    w("The domains are the protection domains of the boot image with their protection keys; the capabilities")
    w("are the ring grants of the table plus each domain's own ring at slot 2. The input ring, device leases,")
    w("the framebuffer and the key-14 shared buffers are outside this model.")
    w("")
    w("Main results: `memory_readers_sound` (in every reachable state, a domain reaches another domain's frame")
    w("only if it is listed in `memoryReaders` of the owner) and its concrete readings, `sexdisplay_memory_private`,")
    w("`sexfiles_memory_confined`, `kaleidoscope_memory_confined`.")
    w("-/")
    w("")
    w("set_option autoImplicit false")
    w("")
    namespace = "SexOSNetworkGenesis" if args.network else "SexOSGenesis"
    w("namespace Mettapedia.Machines.Kernel." + namespace)
    w("")
    w("open Mettapedia.Machines.Kernel")
    w("")
    w("inductive Dom where")
    for name in names:
        w(f"  | {name}")
    w("  deriving DecidableEq, Repr")
    w("")
    w("/-- Protection keys, the table's id column. -/")
    w("def key : Dom → Nat")
    for ident, name in domains:
        w(f"  | .{name} => {ident}")
    w("")
    w("theorem key_inj : ∀ a b, key a = key b → a = b := by")
    w("  intro a b h; cases a <;> cases b <;> first | rfl | (simp [key] at h)")
    w("")
    w("def config : Config Dom where")
    w("  key := key")
    w("  key_inj := key_inj")
    w("  bound := 256")
    w("")
    w("/-- The ring grants: holder, slot, target. -/")
    w("def rows : List (Dom × Nat × Dom) :=")
    body = ", ".join(f"(.{h}, {s}, .{t})" for h, s, t in grants)
    w(f"  [{body}]")
    w("")
    w("/-- The genesis tables: a domain's own ring at slot 2, the first matching row elsewhere. -/")
    w("def caps (d : Dom) (n : Nat) : Option (Cap Dom) :=")
    w("  if n = 2 then some ⟨.ring d, true⟩")
    w("  else (rows.find? fun r => r.1 = d ∧ r.2.1 = n).map fun r => ⟨.ring r.2.2, true⟩")
    w("")
    w("theorem caps_no_frames : ∀ d n f w, caps d n ≠ some ⟨.frame f, w⟩ := by")
    w("  intro d n f w h")
    w("  unfold caps at h")
    w("  split at h")
    w("  · cases h")
    w("  · obtain ⟨r, -, hr⟩ := Option.map_eq_some_iff.mp h")
    w("    cases hr")
    w("")
    w("theorem caps_ring {a b : Dom} {n : Nat} {w : Bool} (h : caps a n = some ⟨.ring b, w⟩) :")
    w("    b = a ∨ (a, n, b) ∈ rows := by")
    w("  unfold caps at h")
    w("  split at h")
    w("  · cases h; exact Or.inl rfl")
    w("  · obtain ⟨r, hr, he⟩ := Option.map_eq_some_iff.mp h")
    w("    cases he")
    w("    have hm := List.mem_of_find?_eq_some hr")
    w("    have hp := List.find?_some hr")
    w("    simp only [decide_eq_true_eq] at hp")
    w("    obtain ⟨h1, h2⟩ := hp")
    w("    right")
    w("    obtain ⟨x, y, z⟩ := r")
    w("    simp only at h1 h2")
    w("    subst h1 h2")
    w("    exact hm")
    w("")
    w("/-- The domains that may ever reach memory owned by `e`: itself and the domains it can send to, which it")
    w("may lend frames to. -/")
    w("def memoryReaders (e : Dom) : List Dom := e :: (rows.filter fun r => r.1 = e).map fun r => r.2.2")
    w("")
    w("theorem memory_readers_sound {s : State Dom} (hs : Reachable config (genesis config caps) s)")
    w("    {d e : Dom} {f : Nat} (hown : s.owner f = some e) (hacc : canAccess s d f = true) :")
    w("    d ∈ memoryReaders e := by")
    w("  by_cases hde : d = e")
    w("  · subst hde; exact List.mem_cons_self")
    w("  obtain ⟨n, w, h⟩ := (genesis_run config caps caps_no_frames hs).2.1 d e f hde hown hacc")
    w("  rcases caps_ring h with h' | h'")
    w("  · exact absurd h' hde")
    w("  · exact List.mem_cons_of_mem _ (List.mem_map.mpr ⟨(e, n, d), List.mem_filter.mpr ⟨h', by simp⟩, rfl⟩)")
    w("")
    w("/-- The compositor sends to no one, so no other domain ever reaches its memory. -/")
    w("theorem sexdisplay_memory_private {s : State Dom} (hs : Reachable config (genesis config caps) s)")
    w("    {d : Dom} {f : Nat} (hown : s.owner f = some .sexdisplay) (hacc : canAccess s d f = true) :")
    w("    d = .sexdisplay := by")
    w("  have h := memory_readers_sound hs hown hacc")
    w("  simpa [memoryReaders, rows] using h")
    w("")
    w("/-- The file server's memory is reached only by itself and the block driver it lends buffers to. -/")
    w("theorem sexfiles_memory_confined {s : State Dom} (hs : Reachable config (genesis config caps) s)")
    w("    {d : Dom} {f : Nat} (hown : s.owner f = some .sexfiles) (hacc : canAccess s d f = true) :")
    w("    d = .sexfiles ∨ d = .sexdrive := by")
    w("  have h := memory_readers_sound hs hown hacc")
    w("  simpa [memoryReaders, rows] using h")
    w("")
    w("/-- The browser may lend its memory only to the network server and compositor. -/" if args.network else
      "/-- The browser's memory is reached only by itself and the network server. -/")
    w("theorem kaleidoscope_memory_confined {s : State Dom} (hs : Reachable config (genesis config caps) s)")
    w("    {d : Dom} {f : Nat} (hown : s.owner f = some .kaleidoscope) (hacc : canAccess s d f = true) :")
    w("    d = .kaleidoscope ∨ d = .sexnet" + (" ∨ d = .sexdisplay" if args.network else "") + " := by")
    w("  have h := memory_readers_sound hs hown hacc")
    w("  simpa [memoryReaders, rows] using h")
    w("")
    w("end Mettapedia.Machines.Kernel." + namespace)
    args.output.write_text("\n".join(lines) + "\n")
    print(args.output)


if __name__ == "__main__":
    main()
